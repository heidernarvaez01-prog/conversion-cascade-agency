<h2>Antes de invertir</h2><ul class="ed-checklist">
  <li>Etiqueta de Google, Meta Pixel o Insight Tag instalada y comprobada en todas las páginas necesarias.</li>
  <li>Eventos relevantes: vista de producto o servicio, inicio de formulario, envío, añadir al carrito, inicio de pago y compra.</li>
  <li>Una conversión principal claramente definida; no todas las interacciones deben contar como resultado.</li>
  <li>Exclusión de compradores, leads ya enviados, equipo interno y tráfico de prueba cuando sea posible.</li>
  <li>Aviso de privacidad y gestión de consentimiento acordes con los países donde operas.</li>
  <li>Parámetros UTM consistentes y una fuente de verdad para ventas o leads, idealmente la tienda o el CRM.</li>
</ul>
